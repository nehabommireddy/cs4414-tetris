use std::path::PathBuf;

use p5_tetris::input::parse_inputs;
use p5_tetris::multiplayer::Multiplayer;
use p5_tetris::resources::Resources;

fn render_side_by_side(mp: &Multiplayer) -> String {
    let p1 = mp.p1().render();
    let p2 = mp.p2().render();
    let mut out = String::new();
    for i in 0..p1.len() {
        for &c in &p1[i] {
            out.push(if c { 'o' } else { '.' });
        }
        out.push_str("    ");
        for &c in &p2[i] {
            out.push(if c { 'o' } else { '.' });
        }
        out.push('\n');
    }
    out
}

fn run_actions(tag: &str, p1_str: &str, p2_str: &str) -> String {
    let resources = Resources::load(&PathBuf::from("resources")).expect("load resources");
    let p1_path = std::env::temp_dir().join(format!("mp_test_{tag}_p1.txt"));
    let p2_path = std::env::temp_dir().join(format!("mp_test_{tag}_p2.txt"));
    std::fs::write(&p1_path, p1_str).unwrap();
    std::fs::write(&p2_path, p2_str).unwrap();
    let p1_actions = parse_inputs(&p1_path).unwrap();
    let p2_actions = parse_inputs(&p2_path).unwrap();
    let mut mp = Multiplayer::new(&resources).unwrap();
    mp.run(&p1_actions, &p2_actions).unwrap();
    render_side_by_side(&mp)
}

